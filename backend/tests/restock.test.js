test('only zero to positive triggers restock', () => {
  assert.equal(isRestock(0, 20), true);
  assert.equal(isRestock(-1, 20), true);
  assert.equal(isRestock(undefined, 20), false);
  for (const [a, b] of [[20, 30], [20, 0], [0, 0]]) assert.equal(isRestock(a, b), false);
});
test('optional out-of-stock search preserves available-first ranking and emergency filters', () => {
  const { rankPharmacies } = require('../services/ranking');
  const base = { name: 'Test', timezone: 'Asia/Colombo', openingHours: Array.from({ length: 7 }, (_, day) => ({ day, allDay: true })), inventory: [{ name: 'Vitamin C', quantity: 0 }] };
  const stock = { ...base, _id: 'stock' }, available = { ...base, _id: 'available', inventory: [{ name: 'Vitamin C', quantity: 2 }] };
  assert.equal(rankPharmacies([stock], { medicine: 'Vitamin C' }).length, 0);
  const results = rankPharmacies([stock, available], { medicine: 'Vitamin C', includeOutOfStock: true });
  assert.deepEqual(results.map(p => p._id), ['available', 'stock']);
  assert.equal(results[1].medicines[0].quantity, 0);
  assert.match(results[1].rankingReason, /Out of stock/);
  assert.equal(rankPharmacies([{ ...stock, openingHours: undefined }], { medicine: 'Vitamin C', includeOutOfStock: true, emergency: true }).length, 0);
});
test('active subscription uniqueness is enforced by a partial unique database index', () => {
  const index = Subscription.schema.indexes().find(([keys]) => keys.customer && keys.pharmacy && keys.medicine);
  assert.equal(index[1].unique, true);
  assert.deepEqual(index[1].partialFilterExpression, { active: true });
});
test('HTTP subscriptions, restock inventory, customer notification ownership and read state', async t => {
  const old = process.env.JWT_SECRET; process.env.JWT_SECRET = 'restock-test';
  t.after(() => { if (old === undefined) delete process.env.JWT_SECRET; else process.env.JWT_SECRET = old; });
  const customer = new mongoose.Types.ObjectId(), other = new mongoose.Types.ObjectId(), owner = new mongoose.Types.ObjectId();
  const pharmacy = new Pharmacy({ owner, name: 'Test Pharmacy', address: 'Colombo', district: 'Colombo', phone: '123', latitude: 6, longitude: 79, inventory: [{ name: 'Vitamin C', quantity: 0 }] });
  const medicine = pharmacy.inventory[0];
  const subscriptions = [], notifications = [];
  const matches = (doc, filter) => Object.entries(filter).every(([key, value]) => String(doc[key]) === String(value));
  const query = docs => ({ session: async () => docs, sort: () => ({ limit: async () => docs, then: (resolve, reject) => Promise.resolve(docs).then(resolve, reject) }) });
  t.mock.method(User, 'findById', id => ({ select: async () => ({ _id: id, role: String(id) === String(owner) ? 'pharmacy_owner' : 'customer' }) }));
  t.mock.method(Pharmacy, 'findById', id => { const p = String(id) === String(pharmacy._id) ? pharmacy : null; return { session: async () => p, then: (resolve, reject) => Promise.resolve(p).then(resolve, reject) }; });
  t.mock.method(Pharmacy, 'updateOne', async () => ({}));
  t.mock.method(pharmacy, 'save', async () => { await pharmacy.validate(); return pharmacy; });
  const session = {};
  t.mock.method(mongoose.connection, 'transaction', async fn => fn(session));
  t.mock.method(Subscription, 'find', filter => query(subscriptions.filter(s => matches(s, filter))));
  t.mock.method(Subscription, 'create', async docs => {
    const data = { ...docs[0], active: true, _id: new mongoose.Types.ObjectId() };
    if (subscriptions.some(s => s.active && matches(s, { customer: data.customer, pharmacy: data.pharmacy, medicine: data.medicine }))) throw Object.assign(new Error(), { code: 11000 });
    subscriptions.push(data); return [data];
  });
  const update = (docs, filter, values) => { const doc = docs.find(d => matches(d, filter)); if (doc) Object.assign(doc, values.$set); return doc || null; };
  t.mock.method(Subscription, 'findOneAndUpdate', async (filter, values) => update(subscriptions, filter, values));
  t.mock.method(Subscription, 'updateOne', async (filter, values) => update(subscriptions, filter, values));
  t.mock.method(Notification, 'create', async (docs, options) => { assert.equal(options.session, session); const n = { ...docs[0], _id: new mongoose.Types.ObjectId(), read: false }; notifications.push(n); return [n]; });
  t.mock.method(Notification, 'find', filter => query(notifications.filter(n => matches(n, filter))));
  t.mock.method(Notification, 'countDocuments', async filter => notifications.filter(n => matches(n, filter)).length);
  t.mock.method(Notification, 'findOneAndUpdate', async (filter, values) => update(notifications, filter, values));
  const app = express(); app.use(express.json()); app.use('/api/pharmacies', require('../routes/pharmacyRoutes')); app.use('/api', require('../routes/alertRoutes'));
  const server = await new Promise(resolve => { const s = app.listen(0, '127.0.0.1', () => resolve(s)); });
  t.after(() => new Promise(resolve => server.close(resolve)));
  async function request(path, method = 'GET', user = customer, body) {
    const r = await fetch(`http://127.0.0.1:${server.address().port}/api${path}`, { method, headers: { 'Content-Type': 'application/json', ...(user ? { Authorization: `Bearer ${jwt.sign({ userId: user }, process.env.JWT_SECRET)}` } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) });
    return { status: r.status, data: await r.json() };
  }
  const body = { pharmacy: String(pharmacy._id), medicine: String(medicine._id), customer: String(other) };
  assert.equal((await request('/restock-subscriptions', 'POST', null, body)).status, 401);
  assert.equal((await request('/restock-subscriptions', 'POST', owner, body)).status, 403);
  assert.equal((await request('/restock-subscriptions', 'POST', customer, { pharmacy: 'bad', medicine: body.medicine })).status, 400);
  assert.equal((await request('/restock-subscriptions', 'POST', customer, { ...body, pharmacy: String(new mongoose.Types.ObjectId()) })).status, 404);
  assert.equal((await request('/restock-subscriptions', 'POST', customer, { ...body, medicine: String(new mongoose.Types.ObjectId()) })).status, 404);
  const statusPath = `/restock-subscriptions?pharmacy=${body.pharmacy}&medicine=${body.medicine}`;
  assert.equal((await request(statusPath)).data.subscribed, false);
  assert.equal((await request('/restock-subscriptions')).data.subscriptions.length, 0);
  assert.equal((await request('/restock-subscriptions?pharmacy=bad&medicine=bad')).status, 400);
  assert.equal((await request(`/restock-subscriptions?pharmacy=${body.pharmacy}`)).status, 400);
  assert.equal((await request(statusPath, 'GET', null)).status, 401);
  assert.equal((await request(statusPath, 'GET', owner)).status, 403);
  const subscribed = await request('/restock-subscriptions', 'POST', customer, body);
  assert.equal((await request(statusPath)).data.subscribed, true);
  assert.equal((await request(statusPath, 'GET', other)).data.subscribed, false);
  assert.equal(subscribed.status, 201); assert.equal(subscribed.data.subscription.customer, String(customer));
  assert.equal((await request('/restock-subscriptions', 'POST', customer, body)).status, 409);
  const cancelPath = `/restock-subscriptions/${subscribed.data.subscription._id}`;
  assert.equal((await request(cancelPath, 'DELETE', other)).status, 404);
  assert.equal((await request('/restock-subscriptions', 'GET', other)).data.subscriptions.length, 0);
  assert.equal((await request(cancelPath, 'DELETE')).status, 200);
  assert.equal((await request(statusPath)).data.subscribed, false);
  assert.equal((await request(cancelPath, 'DELETE')).status, 404);
  assert.equal((await request('/restock-subscriptions', 'POST', customer, body)).status, 201);
  const inventoryPath = `/pharmacies/${pharmacy._id}/inventory/${medicine._id}`;
  assert.equal((await request(inventoryPath, 'PATCH', owner, { quantity: 3 })).status, 200);
  assert.equal(notifications.length, 1); assert.equal(String(notifications[0].user), String(customer));
  assert.equal(notifications[0].message, 'Vitamin C is now available at Test Pharmacy');
  assert.equal(subscriptions[1].active, false); assert.ok(subscriptions[1].fulfilledAt);
  assert.equal((await request('/restock-subscriptions', 'POST', customer, body)).status, 409);
  assert.equal((await request(inventoryPath, 'PATCH', owner, { quantity: 10 })).status, 200);
  assert.equal(notifications.length, 1, 'Low stock to normal stock must not trigger another restock alert');
  assert.equal((await request(inventoryPath, 'PATCH', owner, { quantity: 0 })).status, 200);
  assert.equal(notifications.length, 1);
  const inbox = await request('/notifications'); assert.equal(inbox.data.unreadCount, 1);
  assert.equal((await request('/notifications', 'GET', other)).data.notifications.length, 0);
  assert.equal((await request('/notifications', 'GET', owner)).status, 403);
  const readPath = `/notifications/${notifications[0]._id}/read`;
  assert.equal((await request(readPath, 'PATCH', other)).status, 404);
  assert.equal((await request(readPath, 'PATCH')).status, 200);
  assert.equal((await request('/notifications')).data.unreadCount, 0);
  // A later stock cycle requires a fresh subscription.
  assert.equal((await request('/restock-subscriptions', 'POST', customer, body)).status, 201);
  assert.equal((await request(inventoryPath, 'PATCH', owner, { quantity: 5 })).status, 200);
  assert.equal(notifications.length, 2);
  // Same status handler reports a real unexpected query failure safely.
  const log = t.mock.method(console, 'error', () => {});
  const failedFind = t.mock.method(Subscription, 'find', () => { throw Object.assign(new Error('Sensitive query detail must not be logged'), { name: 'MongoServerError', code: 123 }); });
  const failedRead = await request('/restock-subscriptions');
  assert.equal(failedRead.status, 500);
  assert.equal(failedRead.data.message, 'Unable to process alerts. Please try again.');
  assert.equal(log.mock.callCount(), 1);
  const diagnostics = log.mock.calls[0].arguments.join(' ');
  assert.match(diagnostics, /GET \/restock-subscriptions/);
  assert.match(diagnostics, /MongoServerError/);
  assert.doesNotMatch(diagnostics, /Sensitive query detail/);
  failedFind.mock.restore(); log.mock.restore();
  assert.equal((await request('/restock-subscriptions')).status, 200);
  // Standalone subscription does not execute transactions at all.
  assert.equal((await request(inventoryPath, 'PATCH', owner, { quantity: 0 })).status, 200);
  transactionSupported = false;
  const transactionsBefore = mongoose.connection.transaction.mock.callCount();
  const standalone = await request('/restock-subscriptions', 'POST', other, body);
  assert.equal(standalone.status, 201);
  assert.equal((await request('/restock-subscriptions', 'POST', other, body)).status, 409);
  assert.equal((await request(`/restock-subscriptions/${standalone.data.subscription._id}`, 'DELETE', other)).status, 200);
  assert.equal(mongoose.connection.transaction.mock.callCount(), transactionsBefore);
  assert.equal((await request(inventoryPath, 'PATCH', owner, { quantity: 0 })).status, 200);
  const unsupportedRestock = await request(inventoryPath, 'PATCH', owner, { quantity: 10 });
  assert.equal(unsupportedRestock.status, 503);
  assert.match(unsupportedRestock.data.message, /Inventory was not changed/);
  assert.equal(mongoose.connection.transaction.mock.callCount(), transactionsBefore);
  transactionSupported = true;
});
